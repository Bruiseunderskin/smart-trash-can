#!/usr/bin/env python3
"""Regenerate ui/lvglpro/generated/stc_lp_cat_96.c from the Figma glyph SVGs.

    tools/lvglpro_preview/gen_category_icons.py [--check]

Sources (Figma file g5J7a5DhDuX1UYucR6jitn, page "D-final", state/04-guide 9:75):

    cat0  https://www.figma.com/api/mcp/asset/707f4c61-70ba-48fd-8224-b6de55d06190.svg
    cat1  https://www.figma.com/api/mcp/asset/fb636eaf-2112-40e2-af18-ca41a458ed8d.svg
    cat2  https://www.figma.com/api/mcp/asset/3cb7a426-1286-4a60-beb5-076c7a2631b5.svg
    cat3  https://www.figma.com/api/mcp/asset/5c0256c9-9d81-4edb-a32f-60909a024b42.svg

The asset URLs expire; when they do, re-read state/04-guide with the Figma MCP
`get_design_context` and replace the four constants below.

Rasterising uses sharp-cli 6.1.0 (`npx sharp-cli@6.1.0`), which bundles
librsvg. Output is ARGB8888 96x96 per glyph, matching LVGL's LV_COLOR_FORMAT_ARGB8888
byte order (B, G, R, A).

--check regenerates into a temporary file and compares with the committed one,
exiting non-zero on any difference.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / "ui" / "lvglpro" / "generated" / "stc_lp_cat_96.c"
SHARP_CLI = "sharp-cli@6.1.0"
SIZE = 96

SOURCES = [
    "https://www.figma.com/api/mcp/asset/707f4c61-70ba-48fd-8224-b6de55d06190.svg",
    "https://www.figma.com/api/mcp/asset/fb636eaf-2112-40e2-af18-ca41a458ed8d.svg",
    "https://www.figma.com/api/mcp/asset/3cb7a426-1286-4a60-beb5-076c7a2631b5.svg",
    "https://www.figma.com/api/mcp/asset/5c0256c9-9d81-4edb-a32f-60909a024b42.svg",
]


def download(work: Path) -> list[Path]:
    svgs = []
    for i, url in enumerate(SOURCES):
        dest = work / f"cat{i}.svg"
        subprocess.run(["curl", "-sfL", "-o", str(dest), url], check=True)
        svgs.append(dest)
    return svgs


def rasterise(svgs: list[Path]) -> list[Path]:
    pngs = []
    for i, svg in enumerate(svgs):
        png = svg.with_suffix(".png")
        subprocess.run(
            ["npx", "--yes", SHARP_CLI, "-i", str(svg), "-o", str(png),
             "resize", str(SIZE), str(SIZE)],
            check=True, capture_output=True,
        )
        pngs.append(png)
    return pngs


def emit(pngs: list[Path]) -> str:
    parts = [
        "/* 96 px category glyphs, rasterised from the Figma state/04-guide SVGs.\n"
        f" * Generated by tools/lvglpro_preview/gen_category_icons.py ({SHARP_CLI}).\n"
        " * Do not hand-edit. */\n"
        '#include "lvgl.h"\n',
    ]
    for i, png in enumerate(pngs):
        image = Image.open(png).convert("RGBA")
        if image.size != (SIZE, SIZE):
            sys.exit(f"{png}: expected {SIZE}x{SIZE}, got {image.size}")
        pixels = image.load()
        raw: list[int] = []
        for y in range(SIZE):
            for x in range(SIZE):
                r, g, b, a = pixels[x, y]
                raw += [b, g, r, a]
        name = f"stc_lp_img_cat_{i}_96"
        parts.append(f"static const uint8_t {name}_pixels[] = {{\n")
        for k in range(0, len(raw), 16):
            parts.append(",".join(f"0x{v:02x}" for v in raw[k:k + 16]) + ",\n")
        parts.append("};\n")
        parts.append(
            f"const lv_image_dsc_t {name} = {{\n"
            "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, "
            f".w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 4}}},\n"
            f"    .data_size = sizeof({name}_pixels),\n"
            f"    .data = {name}_pixels,\n}};\n\n"
        )
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="compare with the committed file instead of writing")
    args = parser.parse_args()

    work = Path(tempfile.mkdtemp(prefix="stc-glyphs-"))
    try:
        text = emit(rasterise(download(work)))
    finally:
        shutil.rmtree(work, ignore_errors=True)

    if args.check:
        if not OUT.exists():
            sys.exit(f"{OUT} is missing")
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun without --check")
        print(f"{OUT.name}: up to date")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
